            else
                "• 몸의 에너지는 내 느낌으로 고르는 것이라, 그때그때 기준이 조금씩 다를 수 있어요\n") +
                "• 단어의 위치는 약 3분의 1만 연구(한국어 감정단어 평정, 2005년 대학생 대상)를 따라요. 나머지 3분의 2는 연구에 없는 단어라 AI가 뜻을 보고 정했고, 결과 화면에 'AI 분류'로 표시돼요\n" +
                "• 감성 문장은 앱이 쓴 것이고, 글귀는 그 감정과 어울리는 옛글일 뿐 해석이나 답이 아니에요\n" +
